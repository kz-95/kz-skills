OK = "<!-- ascii-ok -->"  # validate.py lets a line carrying this marker quote non-ASCII
ROW = re.compile(r"^\| ([A-Z]\d+[a-z]?) \| (.*) \|\s*(<!-- ascii-ok -->)?\s*$")
LINK = re.compile(r"\]\(([^)\s]+)\)")
TICK = re.compile(r"`((?:\.\./|\./)[^`\s]+)`")


def read(name):
    return io.open(os.path.join(RULES, name), encoding="utf-8", newline="").read().replace("\r\n", "\n")


def relink(text, src):
    """Rewrite relative links written from rules/<src> so they resolve from packs/."""
    def target(t):
        if t.startswith(("http://", "https://", "mailto:")):
            return t
        if t.startswith("#"):
            return "../rules/" + src + t
        path, _, anchor = t.partition("#")
        new = os.path.relpath(os.path.normpath(os.path.join(RULES, path)), OUT).replace(os.sep, "/")
        return new + ("#" + anchor if anchor else "")
    text = LINK.sub(lambda m: "](" + target(m.group(1)) + ")", text)
    return TICK.sub(lambda m: "`" + target(m.group(1)) + "`", text)


def load():
    rules, texts = {}, {}
    for src in SOURCES:
        texts[src] = read(src)
        for line in texts[src].split("\n"):
            m = ROW.match(line)
            if m:
                rules[m.group(1)] = (src, m.group(2) + (" |  " + OK if m.group(3) else " |"))
    return rules, texts


def section(texts, src, prefix):
    lines = texts[src].split("\n")
    for i, line in enumerate(lines):
        if line.startswith("#") and line.startswith(prefix):
            body = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("#"):
                    break
                body.append(nxt)
            while body and body[-1].strip() in ("", "---"):
                body.pop()
            level = len(line) - len(line.lstrip("#"))
            head = ("### " if level <= 2 else "#### ") + line.lstrip("#").strip()
            return head + " (" + src + ")\n" + relink("\n".join(body), src)
    raise SystemExit("build-packs: no heading starting %r in %s" % (prefix, src))


def command(checks, scheme):
    return "`python %s page.html --checks %s --width 375 --scheme %s`" % (RUN, checks, scheme)


def pack(p, rules, texts):
    out = ["# Pack: %s" % p["name"], "", HEADER,
           "Read this one pack for this type of work, then run its checks; the source rule always wins.", "",
           "Words that route here: %s." % p["keywords"], "", "## Checks", "",
           "Run only these, once, on the screen the work is on, from this folder:", ""]
    for names, scheme, note in p["checks"]:
        out.append("- " + command(names, scheme))
        if note:
            out.append("- " + note)
    out += ["- Point it at that screen: `--hash ROUTE`, `--tap \"#tab,#open\"` (clicked in order), "
            "`--wait %s` (must be visible first), `--storage FILE`, `--expect TEXT`." % p["wait"],
            "- " + WRONG, "- After a fix, re-run only the check that failed.", ""]
    if p["snippets"]:
        out += ["## Start from", ""]
        out += ["- `../snippets/%s`" % s for s in p["snippets"]]
        out.append("")
    out += ["## Rules", "", "| ID | Rule |", "|---|---|"]
    for rid in p["full"]:
        src, text = rules[rid]
        out.append("| %s | %s" % (rid, relink(text, src)))
    for rid in p["brief"]:
        src, text = rules[rid]
        m = re.match(r"\*\*(.+?)\*\*", text)
        first = m.group(1).strip() if m else text.split(". ")[0] + "."
        out.append("| %s | **%s** (brief) |" % (rid, first))
    out.append("")
    if p["brief"]:
        srcs = sorted(set(rules[r][0] for r in p["brief"]))
        out += ["A row marked (brief) is the rule's first sentence only; the full rule is in %s."
                % " and ".join("[%s](../rules/%s)" % (x, x) for x in srcs), ""]
    if p["appendix"]:
        out += ["## From the appendices", ""]
        for src, prefix in p["appendix"]:
            out += [section(texts, src, prefix), ""]
    text = "\n".join(out).rstrip("\n") + "\n"
    for line in text.split("\n"):
        if OK not in line and any(ord(c) > 127 for c in line):
            raise SystemExit("build-packs: pack %s would hold non-ASCII in %r; fix the rule text" % (p["name"], line[:60]))
    return text


def lookup():
    out = ["# Pack lookup", "", HEADER,
           "Match the task's words to one row, read that one pack, run its checks on the screen the work is on.",
           "Two rows match: read both packs. None matches: `../rules/INDEX.md`.", "",
           "| Words in the task | Pack | Checks |", "|---|---|---|"]
    for p in PACKS:
        names = ", ".join(c[0].replace(",", ", ") + (" (both themes)" if c[1] == "both" else "") for c in p["checks"])
        out.append("| %s | [%s](%s.md) | %s |" % (p["keywords"], p["name"], p["name"], names))
    out += ["", "Command, from this folder (one width, the pack's checks only, never all):",
            command("<the pack's checks>", "light"),
            "Point it at the screen the work is on: `--hash ROUTE` opens page.html#ROUTE, "
            "`--tap \"#tab,#open\"` clicks in order, `--wait SELECTOR` must be visible first "
            "(also `--storage FILE`, `--expect TEXT`).", WRONG, ""]
    return "\n".join(out)


def build():
    rules, texts = load()
    files = {"LOOKUP.md": lookup()}
    for p in PACKS:
        files[p["name"] + ".md"] = pack(p, rules, texts)
    return files


def main(argv):
    files = build()
    if "--check" in argv:
        stale = []
        for name, text in files.items():
            path = os.path.join(OUT, name)
            have = io.open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else ""
            if have != text:
                stale.append(name)
        extra = sorted(set(os.listdir(OUT)) - set(files)) if os.path.isdir(OUT) else []
        if stale or extra:
            print("skills/kz-uiuxrule/packs is out of date (%s) - run: python scripts/build-index.py"
                  % ", ".join(stale + ["%s not generated" % e for e in extra]))
            return 1
        print("packs up to date (%d files)" % len(files))
        return 0
    os.makedirs(OUT, exist_ok=True)
    for name, text in files.items():
        io.open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote skills/kz-uiuxrule/packs (%d files)" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
